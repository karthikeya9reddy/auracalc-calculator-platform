import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicDefinitions, publicConverterDefinitions } from '../catalog/public/index.mjs';
import { FIELD_DIRECTORY } from '../catalog/field-directory.mjs';
import { createFieldToolIndex } from '../catalog/field-tool-index.mjs';
import { fieldRoute } from '../catalog/field-route.mjs';
import { generateCalculatorPages } from './generate-pages-lib.mjs';
import { generateMeasurePages } from './generate-measure-pages.mjs';
import { generateStudioPage } from './generate-studio-page.mjs';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputRoot = resolve(projectRoot, 'dist');
const markerPath = resolve(outputRoot, '.auracalc-generated-output');
const legacyMarkerPath = resolve(outputRoot, '.nexora-generated-output');
const publicUrl = process.env.AURACALC_PUBLIC_URL || process.env.NEXORA_PUBLIC_URL;
const baseUrl = publicUrl ? new URL(publicUrl) : null;
if (baseUrl && (baseUrl.protocol !== 'https:' || baseUrl.pathname !== '/' || baseUrl.search || baseUrl.hash || baseUrl.username || baseUrl.password)) {
  throw new Error('AURACALC_PUBLIC_URL must be the HTTPS origin for the deployed site, such as https://example.org/.');
}

try {
  await stat(outputRoot);
  try { await readFile(markerPath, 'utf8'); }
  catch {
    try { await readFile(legacyMarkerPath, 'utf8'); }
    catch { throw new Error('Refusing to replace dist because it does not contain an AuraCalc build marker. Move or rename it yourself if it is your generated build output.'); }
  }
  await rm(outputRoot, { recursive: true, force: true });
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

console.log('Preparing static deployment files…');
await mkdir(outputRoot, { recursive: true });
// Mark ownership before copying so an interrupted build can be retried safely.
await writeFile(markerPath, 'Generated by npm run build. Safe to replace during the next AuraCalc build.\n', 'utf8');
const generatedDirectories = ['calculators', 'converters', 'fields'];
await cp(resolve(projectRoot, 'web'), outputRoot, {
  recursive: true,
  filter: source => {
    const webRoot = resolve(projectRoot, 'web');
    const parts = source.slice(webRoot.length + 1).split(/[/\\]/);
    return parts.length < 2 || !generatedDirectories.includes(parts[0]) || parts[1] === 'index.html';
  },
});
await mkdir(resolve(outputRoot, 'src'), { recursive: true });
await cp(resolve(projectRoot, 'src', 'calculation-core'), resolve(outputRoot, 'src', 'calculation-core'), { recursive: true });
await cp(resolve(projectRoot, 'catalog'), resolve(outputRoot, 'catalog'), { recursive: true });
await cp(resolve(projectRoot, 'prototype'), resolve(outputRoot, 'prototype'), { recursive: true });
await cp(resolve(projectRoot, 'LICENSE'), resolve(outputRoot, 'LICENSE'));
await cp(resolve(projectRoot, 'THIRD_PARTY_NOTICES.md'), resolve(outputRoot, 'THIRD_PARTY_NOTICES.md'));
console.log('Generating catalog routes…');
await generateCalculatorPages(projectRoot, outputRoot);
await generateMeasurePages(projectRoot, outputRoot);
await generateStudioPage(projectRoot, outputRoot);

if (baseUrl) {
  const fieldToolMap = createFieldToolIndex(publicDefinitions);
  const indexableFieldRoutes = FIELD_DIRECTORY.filter(field => fieldToolMap.get(field).length > 0).map(fieldRoute);
  const routes = ['/', '/converters/', '/currency/', '/builder/', '/fields/', '/measure/', '/measure/photo/', '/measure/ar/', '/measure/speed/', ...publicDefinitions.map(definition => `/calculators/${definition.id}/`), ...publicConverterDefinitions.map(definition => `/converters/${definition.id}/`), ...indexableFieldRoutes];
  const entries = routes.map(route => `  <url><loc>${new URL(route, baseUrl).href}</loc></url>`).join('\n');
  await writeFile(resolve(outputRoot, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`, 'utf8');
  for (const route of routes) {
    const pageFile = resolve(outputRoot, route.slice(1), 'index.html');
    const pageHtml = await readFile(pageFile, 'utf8');
    const canonical = `<link rel="canonical" href="${new URL(route, baseUrl).href}">`;
    const canonicalized = /<link rel="canonical" href="[^"]*">/.test(pageHtml)
      ? pageHtml.replace(/<link rel="canonical" href="[^"]*">/, canonical)
      : pageHtml.replace('</head>', `  ${canonical}\n</head>`);
    await writeFile(pageFile, canonicalized, 'utf8');
  }
  await writeFile(resolve(outputRoot, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${new URL('/sitemap.xml', baseUrl).href}\n`, 'utf8');
}

console.log(`AuraCalc static site built in dist with ${publicDefinitions.length} formula calculator pages, ${publicConverterDefinitions.length} converter pages, and ${FIELD_DIRECTORY.length} field pages.`);
