  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => (key.startsWith('nexora-shell-') || key.startsWith('auracalc-shell-')) && key !== CACHE_NAME).map(key => caches.delete(key)))).then(() => self.clients.claim()));
